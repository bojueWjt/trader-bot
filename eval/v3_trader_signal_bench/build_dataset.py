def main() -> None:
    rows = json.loads(SRC.read_text())
    items = []
    for idx, gold in GOLDS.items():
        row = rows[idx]
        items.append(
            {
                "id": gold["id"],
                "source_index": idx,
                "channel_id": row["channel_id"],
                "channel_name": CHANNEL_NAMES.get(row["channel_id"], row["channel_id"]),
                "source_message_id": str(row["source_message_id"]),
                "received_at": row["source_received_at"],
                "text": row["text"],
                "gold": gold,
            }
        )
    items.sort(key=lambda x: x["id"])
    families = {}
    for it in items:
        families[it["gold"]["family"]] = families.get(it["gold"]["family"], 0) + 1
    payload = {
        "title": "v3-trader real channel signal bench",
        "n": len(items),
        "channels": sorted({it["channel_name"] for it in items}),
        "families": families,
        "items": items,
    }
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
    print(f"wrote {OUT} n={len(items)} families={families}")


if __name__ == "__main__":
    main()
